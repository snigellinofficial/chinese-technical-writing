// 引出列举却以句号收尾：列举内容另行分行时，应当改用冒号。
// 判定条件是引出动词之后紧跟“数量加量词”，量词为必需项。
// 排除三类误报：“拥有”“具有”中的单字动词，“只有一个”一类结果句，以及“只能有”一类限制句。
const QUANTITY_UNIT = '[一二三四五六七八九十两0-9]+[个项条类部分章节]';
const INTRO_VERB = '(?:分为|分成|共分|包含|包括|共有|(?<![拥具享只])有)';
const HAS_LIMITER = '只[^，。；：]{0,4}有';
export const LIST_INTRO_PERIOD = new RegExp(
  `^(?!.*${HAS_LIMITER}).*${INTRO_VERB}${QUANTITY_UNIT}[^，。；：、]{0,3}。$`,
);

